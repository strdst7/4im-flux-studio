/**
 * `flux export` — write a preset as a standalone config module.
 *
 * Two shapes:
 *   --format ts   an ES module exporting a typed Partial<FluidConfig>
 *   --format json a plain .json file
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { diffFromDefaults, getPreset, hasPreset, resolveConfig } from "@4im/fluid";
import { boolFlag, stringFlag } from "../args.mjs";
import { bold, dim, green, red } from "../format.mjs";

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function constName(id) {
  const camel = id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

function renderValue(value, indent) {
  if (typeof value === "object" && value !== null) {
    const inner = Object.entries(value)
      .map(([k, v]) => `${" ".repeat(indent + 2)}${k}: ${v},`)
      .join("\n");
    return `{\n${inner}\n${" ".repeat(indent)}}`;
  }
  return String(value);
}

export function renderTs(preset, target = "diff") {
  const config =
    target === "full"
      ? resolveConfig({ preset })
      : diffFromDefaults(getPreset(preset.id).config);

  const body = Object.entries(config)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `  ${key}: ${renderValue(value, 2)},`)
    .join("\n");

  const name = constName(preset.id);

  return `import type { FluidConfig } from "@4im/fluid";

/**
 * ${preset.name}
 * ${preset.group} · family ${preset.family} · variant ${preset.variant}
 *
 * Generated by \`flux export\` from preset "${preset.id}".
 */
export const ${name}: Partial<FluidConfig> = {
${body}
};

export default ${name};
`;
}

export async function exportPreset(positionals, flags) {
  const id = positionals[0];
  if (!id) {
    console.error("flux export needs a preset id — run `flux list` to see them");
    return 1;
  }
  if (!hasPreset(id)) {
    console.error(`unknown preset "${id}"`);
    return 1;
  }

  const format = stringFlag(flags, "format") ?? "ts";
  if (format !== "ts" && format !== "json") {
    console.error(`--format must be ts or json, got "${format}"`);
    return 1;
  }

  const preset = getPreset(id);
  const target = stringFlag(flags, "target") ?? "diff";
  const out = stringFlag(flags, "out") ?? `${id}.${format}`;
  const path = resolve(out);

  const contents =
    format === "json"
      ? JSON.stringify(
          {
            id: preset.id,
            name: preset.name,
            group: preset.group,
            family: preset.family,
            variant: preset.variant,
            ...(target === "full"
              ? { config: resolveConfig({ preset }) }
              : { config: diffFromDefaults(preset.config) }),
          },
          null,
          2
        ) + "\n"
      : renderTs(preset, target);

  if (boolFlag(flags, "dry-run")) {
    process.stdout.write(contents);
    return 0;
  }

  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents, "utf8");
  console.log(green("wrote ") + path + dim(` (${format}, ${target})`));
  return 0;
}

export const exportHelp = `${bold("flux export")} <preset-id> [--format ts|json] [--target diff|full] [--out <path>]

Write a preset as a standalone module.

  --target diff   only the keys this preset changes (default, and what you want
                  when adding a preset back to the repo)
  --target full   every key, merged over the defaults (what you want when
                  copying a look into a non-Flux project)
  --dry-run       print to stdout instead of writing a file`;
